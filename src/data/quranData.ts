export function getGlobalAyahNumber(surahNum: number, ayahIndexZeroBased: number): number {
  let totalBefore = 0;
  for (let i = 0; i < surahNum - 1; i++) {
    totalBefore += AYAH_COUNTS[i] || 0;
  }
  return totalBefore + ayahIndexZeroBased + 1;
}

export function normalizeArabic(text: string): string {
  return text
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[^\u0621-\u064A\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

